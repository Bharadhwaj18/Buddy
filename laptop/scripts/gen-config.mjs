// Writes src/config.ts from the phone app's android/local.properties (git-ignored), so the backend
// address and the public (publishable) key live in one place and never in the repo.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const props = readFileSync(join(here, "../../android/local.properties"), "utf8");
const read = (key) => {
  const line = props.split(/\r?\n/).find((l) => l.startsWith(key + "="));
  return line ? line.slice(key.length + 1).trim() : "";
};
const url = read("supabase.url");
const key = read("supabase.publishableKey");
if (!url || !key) throw new Error("supabase.url / supabase.publishableKey missing from android/local.properties");
writeFileSync(
  join(here, "../src/config.ts"),
  `// Generated by scripts/gen-config.mjs. Do not edit.\nexport const SUPABASE_URL = ${JSON.stringify(url)};\nexport const SUPABASE_KEY = ${JSON.stringify(key)};\n`,
);
console.log("config.ts written");
